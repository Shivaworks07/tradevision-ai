        ServerSignalEngine.Signal s = engine.analyze(candles);

        assertThat(s.direction()).isEqualTo("SHORT");
        assertThat(s.signalLabel()).isEqualTo("SELL");
        assertThat(s.confidence()).isEqualTo(66.0);
        assertThat(s.entry()).isEqualTo(117.08839456529334);
        assertThat(s.stopLoss()).isEqualTo(119.0137593153507);
